"""Generates embedded web assets and optional local TLS certificate assets."""
import gzip
import json
import os

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

project = env.subst("$PROJECT_DIR")  # noqa: F821
web = os.path.join(project, "web")

# Served paths, MIME types and the web/ file behind each. The UI is compiled in as plain C++ arrays
# because the platform's embed options do not link reliably with a PlatformIO ESP-IDF project.
ASSETS = [
    ("index.html", "text/html", ["/", "/index.html"]),
    ("app.js", "text/javascript", ["/app.js"]),
    ("style.css", "text/css", ["/style.css"]),
]


def generate():
    lines = ['// Generated by tools/build_web.py. Do not edit.', '#include "web_assets.h"', ""]
    table = []
    for i, (name, mime, paths) in enumerate(ASSETS):
        with open(os.path.join(web, name), "rb") as fh:
            # mtime=0 keeps the output identical between builds, so unchanged assets do not force a recompile.
            data = gzip.compress(fh.read(), compresslevel=9, mtime=0)
        body = ",".join("0x%02x" % b for b in data)
        lines.append("static const unsigned char d%d[] = {%s};" % (i, body))
        for p in paths:
            table.append('    {"%s", "%s", d%d, %d},' % (p, mime, i, len(data)))
    lines += ["", "const WebAsset kWebAssets[] = {"] + table + ["};",
              "const size_t kWebAssetCount = %d;" % len(table), ""]
    return "\n".join(lines)


def generate_tls_assets():
    cert_path = os.path.join(project, "certs", "server.crt")
    key_path = os.path.join(project, "certs", "server.key")
    cert_exists = os.path.exists(cert_path)
    key_exists = os.path.exists(key_path)
    if cert_exists != key_exists:
        raise OSError("certs/server.crt and certs/server.key must both exist")

    cert = ""
    key = ""
    if cert_exists:
        with open(cert_path, "r", encoding="ascii") as fh:
            cert = fh.read()
        with open(key_path, "r", encoding="ascii") as fh:
            key = fh.read()

    header = """#pragma once
#include <string>

namespace tls_assets {
bool load(std::string& certPem, std::string& keyPem);
}
"""
    source = """#include "cert_assets.h"

namespace {
const char kCert[] = %s;
const char kKey[] = %s;
}

namespace tls_assets {
bool load(std::string& certPem, std::string& keyPem) {
    if (!kCert[0] || !kKey[0]) return false;
    certPem.assign(kCert);
    keyPem.assign(kKey);
    return true;
}
}
""" % (json.dumps(cert), json.dumps(key))
    return header, source


def write_generated(path, content):
    old = None
    if os.path.exists(path):
        with open(path, "r", encoding="ascii") as fh:
            old = fh.read()
    if old != content:
        with open(path, "w", encoding="ascii", newline="\n") as fh:
            fh.write(content)


out_dir = os.path.join(project, "src", "generated")
try:
    content = generate()
    tls_header, tls_source = generate_tls_assets()
except OSError as err:
    print("ERROR: cannot generate firmware assets: %s" % err)
    env.Exit(1)  # noqa: F821

os.makedirs(out_dir, exist_ok=True)
write_generated(os.path.join(out_dir, "web_assets.cpp"), content)
write_generated(os.path.join(out_dir, "cert_assets.h"), tls_header)
write_generated(os.path.join(out_dir, "cert_assets.cpp"), tls_source)
